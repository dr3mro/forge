# shellcheck shell=bash
# shellcheck disable=SC2034  # globals consumed by other modules
# Forge CMake module — render managed CMake files from the manifest.
# API:
#   cmake_render_all DIR          # render every managed file into DIR
#   cmake_managed_files [DIR]     # relative paths, including dependencies rendered in DIR
#   normalize_generator NAME
#   compute_fingerprint PROFILE TOOLCHAIN VCPKG_MANIFEST
#   cmake_configure DIR PROFILE TOOLCHAIN VCPKG_MANIFEST FRESH
#   cmake_prepare_file_api BUILD_DIR
#   cmake_list_executables BUILD_DIR
#   find_executable NAME BUILD_DIR
#   resolve_build_dir [PROFILE]    # echoes stable build dir
#   link_compile_commands BUILD_DIR
# Inputs: FORGE_MANIFEST_JSON (manifest_load), FORGE_ROOT.
# Outputs: generated files; stdout paths for query helpers.
# Side effects: writes only in cmake_render_all/configure/prepare_file_api.

declare -A FORGE_LINK_MAP=()

# List the generated files tracked by sync.
cmake_managed_files() {
  printf '%s\n' \
    CMakeLists.txt \
    CMakePresets.json \
    conanfile.txt \
    cmake/Version.cmake \
    cmake/VersionSource.cmake \
    cmake/ProjectOptions.cmake \
    cmake/Dependencies.cmake \
    cmake/Workspace.cmake \
    cmake/Targets.cmake \
    cmake/Testing.cmake

  local dir="${1:-}" file
  if [[ -n "${dir}" ]]; then
    for file in "${dir}"/cmake/deps/*.cmake; do
      [[ ! -f "${file}" ]] || printf '%s\n' "${file#"${dir}/"}"
    done
  fi
  return 0
}

# Translate the manifest generator name to its CMake spelling.
normalize_generator() {
  case "$1" in
    "Unix Makefiles" | Make | make) printf '%s' "Unix Makefiles" ;;
    "Ninja Multi-Config")           printf '%s' "Ninja Multi-Config" ;;
    *)                              printf '%s' "Ninja" ;;
  esac
}

# --- Renderers (stdout) ----------------------------------------------------
render_cmake_lists() {
  local name version languages=CXX
  name=$(mq '.package.name')
  version=$(mq '.package.version')
  if [[ "$(mq 'any((.bin // []) + (.lib // []) + (.test // []) | .[]; .path | endswith(".c"))')" == true ]]; then
    languages=C
    if [[ "$(mq 'any((.bin // []) + (.lib // []) + (.test // []) | .[]; .path | endswith(".c") | not)')" == true ]]; then
      languages="C CXX"
    fi
  fi
  cat <<EOF
# Generated by Forge. Managed by \`forge sync\`.
# Edit freely; run \`forge sync --diff\` after changing Forge.toml.
cmake_minimum_required(VERSION 3.25)

include(cmake/Version.cmake)
forge_project_version(forge_version ${version})
project(${name} VERSION \${forge_version} LANGUAGES ${languages})

include(cmake/ProjectOptions.cmake)
forge_project_options()
include(user.cmake OPTIONAL)
option(FORGE_CLANG_DIAGNOSTICS "Enable Cargo-style Clang diagnostics" ON)
if(FORGE_CLANG_DIAGNOSTICS AND
   (CMAKE_C_COMPILER_ID MATCHES "Clang" OR CMAKE_CXX_COMPILER_ID MATCHES "Clang"))
  add_compile_options(
    -fcolor-diagnostics
    -fdiagnostics-show-option
    -fdiagnostics-show-note-include-stack
    -ferror-limit=3
    -fno-elide-type
    -fdiagnostics-show-template-tree
    -Wall
    -Wextra
    -Wpedantic
  )
endif()
include(cmake/VersionSource.cmake)
forge_configure_version_source()
include(CTest)

include(cmake/Dependencies.cmake)
include(cmake/Workspace.cmake)
forge_add_workspace_members()
include(cmake/Targets.cmake)

if(BUILD_TESTING)
  include(cmake/Testing.cmake)
endif()
EOF
}

# Resolve the project version from a Git tag or the manifest default.
render_version() {
  cat <<'EOF'
# Generated by Forge. Managed by `forge sync`.
function(forge_project_version result fallback)
  set(version "${fallback}")
  if(EXISTS "${CMAKE_CURRENT_SOURCE_DIR}/version.cpp.in")
    file(STRINGS "${CMAKE_CURRENT_SOURCE_DIR}/version.cpp.in" tag_line
      REGEX [=[^inline constexpr char forge_version\[\] = "v?[0-9]+(\.[0-9]+)*";$]=])
    if(tag_line MATCHES [=["v?([0-9]+(\.[0-9]+)*)"]=])
      set(version "${CMAKE_MATCH_1}")
    endif()
  endif()
  set(${result} "${version}" PARENT_SCOPE)
endfunction()
EOF
}

# Configure the source fragment used by scaffolded binaries.
render_version_source() {
  cat <<'EOF'
# Generated by Forge. Managed by `forge sync`.
function(forge_configure_version_source)
  if(EXISTS "${CMAKE_CURRENT_SOURCE_DIR}/version.cpp.in")
    configure_file(version.cpp.in forge-version.cpp @ONLY)
  endif()
endfunction()
EOF
}

# Set directory-wide defaults before declaring any targets.
render_project_options() {
  local cppstd
  cppstd=$(mq '.package.cppstd')
  cat <<EOF
# Generated by Forge. Managed by \`forge sync\`.
function(forge_project_options)
  set(CMAKE_CXX_STANDARD ${cppstd} PARENT_SCOPE)
  set(CMAKE_CXX_STANDARD_REQUIRED ON PARENT_SCOPE)
  set(CMAKE_CXX_EXTENSIONS OFF PARENT_SCOPE)
  set(CMAKE_EXPORT_COMPILE_COMMANDS ON PARENT_SCOPE)
EOF
  # Bracket literals preserve values without CMake interpolation or escaping.
  mq '
    (.cmake.variables // {}) | to_entries[]
    | .key as $key
    | (.value | if type == "boolean" then (if . then "ON" else "OFF" end) else tostring end) as $value
    | ("=" | until(. as $equals | (($value + "]") | contains("]" + $equals + "]") | not); . + "=")) as $delimiter
    | "  set(\($key) [\($delimiter)[\n\($value)]\($delimiter)] PARENT_SCOPE)"
  ' || return 1
  printf 'endfunction()\n'
}

# Write the debug and release configure presets.
render_cmake_presets() {
  local gen
  gen=$(normalize_generator "$(mq '.build.generator // "Ninja"')")
  jq -n --arg gen "${gen}" '{
    version: 3,
    cmakeMinimumRequired: {major: 3, minor: 25, patch: 0},
    configurePresets: [
      {
        name: "debug", displayName: "Debug", generator: $gen,
        binaryDir: "${sourceDir}/target/debug",
        cacheVariables: {CMAKE_BUILD_TYPE: "Debug"}
      },
      {
        name: "release", displayName: "Release", generator: $gen,
        binaryDir: "${sourceDir}/target/release",
        cacheVariables: {CMAKE_BUILD_TYPE: "Release"}
      }
    ],
    buildPresets: [
      {name: "debug", configurePreset: "debug"},
      {name: "release", configurePreset: "release"}
    ],
    testPresets: [
      {name: "debug", configurePreset: "debug", output: {outputOnFailure: true}},
      {name: "release", configurePreset: "release", output: {outputOnFailure: true}}
    ]
  }'
}

# Write a Conan text recipe for the selected requirements.
render_conanfile() {
  local entry ref opts key val pkg
  local -a entries=()
  if [[ "${FORGE_CONAN_REQUIREMENTS_MODE:-local}" == "graph" \
        && ${#FORGE_CONAN_ALL_REFS[@]} -gt 0 ]]; then
    entries=("${FORGE_CONAN_ALL_REFS[@]}")
  else
    while IFS=$'\t' read -r ref opts; do
      [[ -n "${ref}" ]] && entries+=("${ref}"$'\t'"${opts}")
    done < <(mq '(.dependencies // {}) | to_entries[] | select(.value.source == "conan") | [.value.ref, ((.value.conan_options // {}) | tojson)] | @tsv')
  fi

  local line
  while IFS= read -r line || [[ -n "${line}" ]]; do
    case "${line}" in
      '{{REQUIRES}}')
        for entry in "${entries[@]}"; do
          printf '%s\n' "${entry%%$'\t'*}"
        done ;;
      '{{OPTIONS}}')
        for entry in "${entries[@]}"; do
          IFS=$'\t' read -r ref opts <<< "${entry}"
          pkg="${ref%%/*}"
          while IFS=$'\t' read -r key val; do
            [[ -n "${key}" ]] && printf '%s/*:%s=%s\n' "${pkg}" "${key}" "${val}"
          done < <(printf '%s' "${opts}" | jq -r 'to_entries[] | [.key, (.value | if . == true then "True" elif . == false then "False" else tostring end)] | @tsv')
        done ;;
      *) printf '%s\n' "${line}" ;;
    esac
  done < "${FORGE_HOME}/templates/base/conanfile.txt.tpl"
}

# Keep case-distinct aliases separate on case-insensitive filesystems.
# Manifest aliases cannot contain hyphens, so each uppercase escape is unique.
_cmake_dependency_dir_name() {
  local key="$1" index char name=""
  for (( index = 0; index < ${#key}; index++ )); do
    char="${key:index:1}"
    case "${char}" in
      [A-Z]) name+="-${char,,}" ;;
      *) name+="${char}" ;;
    esac
  done
  printf '%s' "${name}"
}

# Render one module per dependency, in package, Git, then path order.
render_dependencies() {
  local dir="$1" key source first second dir_name
  printf '# Generated by Forge. Managed by `forge sync`.\n'
  printf '# Conan packages are provided by CMakeDeps via the generated toolchain.\n\n'
  printf 'function(forge_add_dependencies)\n'
  mkdir -p "${dir}/cmake/deps" || return 1
  while IFS=$'\t' read -r key source first second; do
    dir_name=$(_cmake_dependency_dir_name "${key}")
    printf '  include(cmake/deps/%s.cmake)\n' "${dir_name}"
    {
      printf '# Generated by Forge. Managed by `forge sync`.\nfunction(forge_load_dependency)\n'
      case "${source}" in
        conan)
          if [[ "${second}" =~ ^[0-9]+(\.[0-9]+){0,3}$ ]]; then
            printf '  find_package(%s %s CONFIG REQUIRED GLOBAL)\n' "${first}" "${second}"
          else
            printf '  find_package(%s CONFIG REQUIRED GLOBAL)\n' "${first}"
          fi
          ;;
        vcpkg)
          # Try the Find module before CONFIG mode, even with Conan's toolchain.
          printf '  find_package(%s MODULE QUIET GLOBAL)\n' "${first}"
          printf '  if(NOT TARGET %s)\n    find_package(%s CONFIG REQUIRED GLOBAL)\n  endif()\n' "${second}" "${first}"
          ;;
        git)
          printf '  include(FetchContent)\n'
          printf '  FetchContent_Declare(%s\n    GIT_REPOSITORY "%s"\n    GIT_TAG %s\n  )\n' "${key}" "${first}" "${second}"
          printf '  FetchContent_MakeAvailable(%s)\n' "${key}"
          ;;
        path)
          printf '  add_subdirectory("${PROJECT_SOURCE_DIR}/%s" "${PROJECT_BINARY_DIR}/%s")\n' "${first}" "${dir_name}"
          ;;
      esac
      printf 'endfunction()\n\nforge_load_dependency()\n'
    } > "${dir}/cmake/deps/${dir_name}.cmake" || return 1
  done < <(mq '
    (.dependencies // {} | to_entries) as $deps
    | [["conan", "vcpkg"], ["git"], ["path"]][] as $sources
    | $deps[] | .key as $key | .value | .source as $source
    | select($sources | index($source))
    | [$key, $source] + (
        if $source == "conan" then
          (.ref | split("/")) as $ref | [(.cmake_package // $ref[0]), ($ref[1] // "")]
        elif $source == "vcpkg" then [.cmake_package, .cmake_target]
        elif $source == "git" then [.url, .rev]
        else [.path] end
      ) | @tsv')
  printf 'endfunction()\n\nforge_add_dependencies()\n'
}

# Add workspace members in the parent project directory scope.
render_workspace() {
  local member bin_name
  printf '# Generated by Forge. Managed by `forge sync`.\n'
  printf 'function(forge_add_workspace_members)\n'
  while IFS= read -r member; do
    [[ -n "${member}" ]] || continue
    bin_name="${member//\//_}"
    printf '  add_subdirectory("%s" "ws_%s")\n' "${member}" "${bin_name}"
  done < <(workspace_members)
  printf 'endfunction()\n'
}

# List the workspace members declared in the current manifest.
workspace_members() {
  mq '(.workspace.members // [])[]'
}

# Target names exported by every reachable member (recursively), so any
# project in the graph can link a nested library by name.
workspace_member_targets() {
  local node json
  workspace_collect_graph "${FORGE_ROOT}"
  for node in "${FORGE_GRAPH_NODES[@]}"; do
    [[ "${node}" == "${FORGE_ROOT}" ]] && continue
    [[ -f "${node}/Forge.toml" ]] || continue
    json=$(manifest_to_json "${node}/Forge.toml") || continue
    printf '%s' "${json}" | jq -r '((.bin // []) + (.lib // []) + (.test // []) | .[].name)'
  done
}

# Map logical dependency names to CMake link targets.
_build_link_map() {
  FORGE_LINK_MAP=()
  local key target name
  while IFS=$'\t' read -r key target; do
    [[ -n "${key}" ]] && FORGE_LINK_MAP["${key}"]="${target}"
  done < <(mq '(.dependencies // {}) | to_entries[] | [.key, .value.cmake_target] | @tsv')
  while IFS= read -r name; do
    [[ -n "${name}" ]] && FORGE_LINK_MAP["${name}"]="${name}"
  done < <(mq '((.bin // []) + (.lib // []) + (.test // []) | .[].name)')
  while IFS= read -r name; do
    [[ -n "${name}" ]] && FORGE_LINK_MAP["${name}"]="${name}"
  done < <(workspace_member_targets)
}

# List legacy implicit links. Packages added with an explicit CMake package are scoped to selected targets.
_default_links() {
  local kind="$1" out="" t
  while IFS= read -r t; do
    [[ -n "${t}" ]] && out+=" ${t}"
  done < <(mq '(.dependencies // {})[] | select(has("cmake_package") | not) | .cmake_target')
  if [[ "${kind}" == "test" ]]; then
    while IFS= read -r t; do
      [[ -n "${t}" ]] && out+=" ${t}"
    done < <(mq '(.lib // [])[] | .name')
  fi
  printf '%s' "${out# }"
}

# Resolve the dependency aliases in a target's links array.
_resolve_links() {
  local kind="$1" links="$2" has_links="$3" out="" t
  local -a arr=()
  if [[ "${has_links}" == "true" ]]; then
    read -r -a arr <<< "${links}"
    for t in "${arr[@]}"; do
      out+=" ${FORGE_LINK_MAP[${t}]:-${t}}"
    done
  else
    read -r -a arr <<< "$(_default_links "${kind}")"
    for t in "${arr[@]}"; do
      out+=" ${t}"
    done
  fi
  printf '%s' "${out# }"
}

# Emit the CMake rules for the manifest's libraries, binaries, and tests.
render_targets() {
  _build_link_map
  local kind name path links has_links resolved command linkage
  printf '# Generated by Forge. Managed by `forge sync`.\nfunction(forge_add_targets)\n'
  while IFS=$'\t' read -r kind name path linkage has_links links; do
    [[ -n "${name}" ]] || continue
    # An empty links array historically uses the legacy dependency defaults.
    if [[ -z "${links}" ]]; then has_links=false; fi
    resolved=$(_resolve_links "${kind}" "${links}" "${has_links}")
    command=executable
    if [[ "${kind}" == lib ]]; then command=library; fi
    if [[ "${linkage}" == legacy ]]; then
      printf '\n  add_%s(%s %s)\n' "${command}" "${name}" "${path}"
    else
      printf '\n  add_library(%s %s %s)\n' "${name}" "${linkage}" "${path}"
      case "${linkage}" in
        STATIC) printf '  set_target_properties(%s PROPERTIES POSITION_INDEPENDENT_CODE ON)\n' "${name}" ;;
        SHARED)
          if [[ ! -f "${FORGE_ROOT}/include/${name}_export.h" ]]; then
            printf '  set_target_properties(%s PROPERTIES WINDOWS_EXPORT_ALL_SYMBOLS ON)\n' "${name}"
          fi ;;
      esac
    fi
    case "${kind}" in
      lib)
        printf '  target_include_directories(%s PUBLIC "${CMAKE_CURRENT_SOURCE_DIR}/include")\n' "${name}"
        if [[ -f "${FORGE_ROOT}/include/${name}_export.h" ]]; then
          if [[ "${linkage}" == SHARED ]]; then
            printf '  target_compile_definitions(%s PUBLIC FORGE_%s_SHARED)\n' "${name}" "${name}"
            printf '  set_target_properties(%s PROPERTIES C_VISIBILITY_PRESET hidden CXX_VISIBILITY_PRESET hidden)\n' "${name}"
          elif [[ "${linkage}" == legacy ]]; then
            printf '  target_compile_definitions(%s PUBLIC "$<$<STREQUAL:$<TARGET_PROPERTY:%s,TYPE>,SHARED_LIBRARY>:FORGE_%s_SHARED>")\n' \
              "${name}" "${name}" "${name}"
          fi
        fi ;;
      bin)
        if [[ -f "${FORGE_ROOT}/version.cpp.in" ]]; then
          printf '  target_include_directories(%s PRIVATE "${CMAKE_CURRENT_BINARY_DIR}")\n' "${name}"
        fi ;;
    esac
    if [[ -n "${resolved}" ]]; then
      printf '  target_link_libraries(%s PRIVATE %s)\n' "${name}" "${resolved}"
    fi
  done < <(mq '
    ["lib", "bin", "test"][] as $kind | (.[$kind] // [])[]
    | [$kind, .name, .path, (if has("type") then .type | ascii_upcase else "legacy" end), (has("links") | tostring), ((.links // []) | join(" "))] | @tsv
  ')
  printf 'endfunction()\n\nforge_add_targets()\n'
}

# Register manifest test executables with CTest.
render_testing() {
  local name
  printf '# Generated by Forge. Managed by `forge sync`.\nfunction(forge_register_tests)\n'
  while IFS= read -r name; do
    [[ -n "${name}" ]] || continue
    printf '  add_test(NAME %s COMMAND %s)\n' "${name}" "${name}"
  done < <(mq '(.test // [])[] | .name')
  printf 'endfunction()\n\nforge_register_tests()\n'
}

# Render the Forge-managed files for one project.
cmake_render_all() {
  local dir="$1"
  mkdir -p "${dir}/cmake" &&
  render_cmake_lists      > "${dir}/CMakeLists.txt" &&
  render_cmake_presets    > "${dir}/CMakePresets.json" &&
  render_version          > "${dir}/cmake/Version.cmake" &&
  render_version_source   > "${dir}/cmake/VersionSource.cmake" &&
  render_project_options  > "${dir}/cmake/ProjectOptions.cmake" &&
  render_workspace        > "${dir}/cmake/Workspace.cmake" &&
  render_dependencies "${dir}" > "${dir}/cmake/Dependencies.cmake" &&
  render_targets          > "${dir}/cmake/Targets.cmake" &&
  render_testing          > "${dir}/cmake/Testing.cmake" || return 1

  if conan_has_deps || [[ "${FORGE_CONAN_REQUIREMENTS_MODE}" == graph && ${#FORGE_CONAN_ALL_REFS[@]} -gt 0 ]]; then
    render_conanfile > "${dir}/conanfile.txt"
  fi
}

# --- Fingerprint / configure ----------------------------------------------
compute_fingerprint() {
  local profile="$1" toolchain="${2:-}" vcpkg_manifest="$3" parts="" conan_script=""
  parts+="compiler=$(c++ --version 2>/dev/null | head -1)"
  parts+="|generator=$(normalize_generator "$(mq '.build.generator // "Ninja"')")"
  parts+="|arch=$(uname -m)"
  parts+="|profile=${profile}"
  parts+="|cmake=$(cmake --version 2>/dev/null | head -1)"
  parts+="|args=$(printf '%s\n' "${FORGE_EXTRA_CMAKE_ARGS[@]}")"
  if [[ -n "${toolchain}" ]]; then
    parts+="|toolchain=${toolchain}:$(sha256_file "${toolchain}")"
  fi
  if [[ -n "${FORGE_SANITIZER:-}" ]]; then
    parts+="|sanitizer=${FORGE_SANITIZER}"
  fi
  if conan_graph_has_deps; then
    conan_script=$(conan profile show 2>/dev/null)
    parts+="|conan=$(sha256_str "${conan_script}"):$(conan_manifest_sha):$(sha256_file "${FORGE_ROOT}/conan.lock")"
  fi
  local vcpkg_toolchain
  if [[ -n "${vcpkg_manifest}" ]]; then
    vcpkg_toolchain="${VCPKG_ROOT:-}/scripts/buildsystems/vcpkg.cmake"
    parts+="|vcpkg=${VCPKG_ROOT:-}:${vcpkg_manifest}"
    if [[ -f "${vcpkg_toolchain}" ]]; then
      parts+=":$(sha256_file "${vcpkg_toolchain}")"
      parts+=":$(git -C "${VCPKG_ROOT}" rev-parse HEAD 2>/dev/null || true)"
    fi
  fi
  sha256_str "${parts}" | cut -c1-12
}

# Resolve a stable profile directory. Sanitizers have their own subtree.
resolve_build_dir() {
  local profile="${1:-}"
  [[ -n "${profile}" ]] || profile=$(mq '.build.default_profile // "debug"')
  [[ "${profile}" =~ ^[A-Za-z_][A-Za-z0-9_-]*$ ]] || return "${EXIT_USAGE}"
  if [[ -n "${FORGE_SANITIZER:-}" ]]; then
    printf '%s' "${FORGE_ROOT}/target/sanitizers/${FORGE_SANITIZER}/${profile}"
  else
    printf '%s' "${FORGE_ROOT}/target/${profile}"
  fi
}

cmake_check_build_path() {
  local path="$1"
  while [[ "${path}" == "${FORGE_ROOT}/target" || "${path}" == "${FORGE_ROOT}/target/"* ]]; do
    [[ ! -L "${path}" ]] || die "${EXIT_CONFLICT}" "refusing to build through a symlink: ${path}"
    path="${path%/*}"
  done
}

# Check that both the CMake cache and generator output exist.
cmake_is_configured() {
  local build_dir="$1" gen="$2" marker
  [[ -f "${build_dir}/CMakeCache.txt" ]] || return 1
  case "${gen}" in
    Ninja*) marker="build.ninja" ;;
    *)      marker="Makefile" ;;
  esac
  [[ -f "${build_dir}/${marker}" ]] || return 1
  return 0
}

# Request a codemodel reply at the next CMake configure.
cmake_prepare_file_api() {
  local build_dir="$1"
  mkdir -p "${build_dir}/.cmake/api/v1/query"
  : > "${build_dir}/.cmake/api/v1/query/codemodel-v2"
}

# Configure the project through its preset, refreshing an existing cache if needed.
cmake_configure() {
  local build_dir="$1" profile="$2" toolchain="$3" vcpkg_manifest="$4" fresh="$5"
  if (( ! FORGE_DRY_RUN )); then
    if [[ -n "${vcpkg_manifest}" ]]; then
      vcpkg_prepare_configure "${build_dir}" "${toolchain}" "${vcpkg_manifest}"
      toolchain=""
    fi
    cmake_prepare_file_api "${build_dir}"
  fi
  local -a args=(--preset "${profile}" -S "${FORGE_ROOT}" -B "${build_dir}")
  if (( fresh )); then args+=(--fresh); fi
  [[ -n "${toolchain}" ]] && args+=("-DCMAKE_TOOLCHAIN_FILE=${toolchain}")
  args+=("${FORGE_EXTRA_CMAKE_ARGS[@]}")
  run_cmd cmake "${args[@]}" \
    || die "${EXIT_BUILD}" "CMake configure failed for '${profile}'"
}

# List executable target names from the CMake File API reply.
cmake_list_executables() {
  local build_dir="$1" reply dir jf
  reply=$(find "${build_dir}/.cmake/api/v1/reply" -name 'codemodel-v2-*.json' -print -quit 2>/dev/null)
  [[ -n "${reply}" ]] || return 1
  dir=$(dirname -- "${reply}")
  while IFS= read -r jf; do
    [[ -f "${dir}/${jf}" ]] || continue
    [[ "$(jq -r '.type' "${dir}/${jf}")" == "EXECUTABLE" ]] || continue
    jq -r '.name' "${dir}/${jf}"
  done < <(jq -r '.configurations[0].targets[] | .jsonFile' "${reply}")
}

# Resolve an executable's real path from the CMake File API codemodel.
cmake_executable_path() {
  local name="$1" build_dir="$2" reply dir jf n artifact
  reply=$(find "${build_dir}/.cmake/api/v1/reply" -name 'codemodel-v2-*.json' -print -quit 2>/dev/null)
  [[ -n "${reply}" ]] || return 1
  dir=$(dirname -- "${reply}")
  while IFS= read -r jf; do
    [[ -f "${dir}/${jf}" ]] || continue
    n=$(jq -r '.name' "${dir}/${jf}")
    [[ "${n}" == "${name}" ]] || continue
    [[ "$(jq -r '.type' "${dir}/${jf}")" == "EXECUTABLE" ]] || continue
    artifact=$(jq -r '.artifacts[0].path // empty' "${dir}/${jf}")
    [[ -n "${artifact}" ]] || return 1
    # Artifact paths are relative to the top-level build directory or absolute.
    if [[ "${artifact}" == /* ]]; then
      printf '%s\n' "${artifact}"
    else
      printf '%s\n' "${build_dir}/${artifact}"
    fi
    return 0
  done < <(jq -r '.configurations[0].targets[] | .jsonFile' "${reply}")
  return 1
}

# Look for a built executable in common generator output locations.
find_executable() {
  local name="$1" build_dir="$2" c
  for c in "${build_dir}/${name}" "${build_dir}/${name}.exe" \
           "${build_dir}/Debug/${name}" "${build_dir}/Release/${name}"; do
    [[ -x "${c}" ]] && { printf '%s\n' "${c}"; return 0; }
  done
  c=$(find "${build_dir}" -maxdepth 3 -type f -name "${name}" -perm -u+x -print -quit 2>/dev/null)
  [[ -n "${c}" ]] && { printf '%s\n' "${c}"; return 0; }
  return 1
}

# Publish the active build's database through stable build and editor paths.
link_compile_commands() {
  local build_dir="$1"
  [[ -f "${build_dir}/compile_commands.json" ]] || return 0

  python3 - "${FORGE_ROOT}" "${build_dir}" "${FORGE_LINK_COMPILE_COMMANDS}" <<'PYTHON' \
    || warn "could not refresh compile_commands.json links"
import os
import re
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

root, build = map(Path, sys.argv[1:3])
force = sys.argv[3] == "1"
target = root / "target"
name = "compile_commands.json"
build_pattern = r"[A-Za-z_][A-Za-z0-9_-]*/compile_commands\.json"
owned_pattern = r"(?:debug|release|[A-Za-z_][A-Za-z0-9_-]*-[0-9a-f]{12})/compile_commands\.json"

def publish(link, destination, owned, replace=False):
    if link.is_symlink():
        previous = os.readlink(link)
        if previous == destination:
            return True
        if not replace and not re.fullmatch(owned, previous):
            return False
    elif link.exists():
        if not replace or not link.is_file():
            return False
    else:
        link.symlink_to(destination)
        return True

    with TemporaryDirectory(dir=link.parent) as temporary:
        staging = Path(temporary) / name
        staging.symlink_to(destination)
        os.replace(staging, link)
    return True

if target.is_symlink() or build.is_symlink() or build.parent != target:
    sys.exit("refusing to publish a compilation database through an indirect build path")
relative = (build / name).relative_to(target).as_posix()
if not re.fullmatch(build_pattern, relative):
    sys.exit("refusing to publish a compilation database outside a Forge build directory")
if not publish(target / name, relative, owned_pattern):
    sys.exit(f"leaving user-owned {target / name} in place")
if not publish(root / name, f"target/{name}", f"target/{owned_pattern}", force):
    sys.exit(f"leaving user-owned {root / name} in place (use --link-compile-commands to replace it)")
PYTHON
}
