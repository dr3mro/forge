# shellcheck shell=bash
# shellcheck disable=SC2034  # globals consumed by other modules
# Forge CMake module — render managed CMake files from the manifest.
# API:
#   cmake_render_all DIR          # render every managed file into DIR
#   cmake_managed_files           # print relative paths, one per line
#   normalize_generator NAME
#   compute_fingerprint PROFILE [TOOLCHAIN]
#   cmake_configure BUILD_DIR PROFILE GENERATOR [TOOLCHAIN]
#   cmake_prepare_file_api BUILD_DIR
#   cmake_list_executables BUILD_DIR
#   find_executable NAME BUILD_DIR
#   resolve_build_dir [PROFILE]   # echoes fingerprinted build dir
#   link_compile_commands BUILD_DIR
# Inputs: FORGE_MANIFEST_JSON (manifest_load), FORGE_ROOT.
# Outputs: generated files; stdout paths for query helpers.
# Side effects: writes only in cmake_render_all/configure/prepare_file_api.

declare -A FORGE_LINK_MAP=()

# List the generated files tracked by sync.
cmake_managed_files() {
  printf '%s\n' \
    CMakeLists.txt \
    CMakePresets.json \
    conanfile.txt \
    cmake/Dependencies.cmake \
    cmake/Targets.cmake \
    cmake/Testing.cmake
}

# Translate the manifest generator name to its CMake spelling.
normalize_generator() {
  case "$1" in
    "Unix Makefiles" | Make | make) printf '%s' "Unix Makefiles" ;;
    "Ninja Multi-Config")           printf '%s' "Ninja Multi-Config" ;;
    *)                              printf '%s' "Ninja" ;;
  esac
}

# --- Renderers (stdout) ----------------------------------------------------
render_cmake_lists() {
  local name version cppstd languages=CXX
  name=$(mq '.package.name')
  version=$(mq '.package.version')
  cppstd=$(mq '.package.cppstd')
  if [[ "$(mq 'any((.bin // []) + (.lib // []) + (.test // []) | .[]; .path | endswith(".c"))')" == true ]]; then
    languages=C
    if [[ "$(mq 'any((.bin // []) + (.lib // []) + (.test // []) | .[]; .path | endswith(".c") | not)')" == true ]]; then
      languages="C CXX"
    fi
  fi
  cat <<EOF
# Generated by Forge. Managed by \`forge sync\`.
# Edit freely; run \`forge sync --diff\` after changing Forge.toml.
cmake_minimum_required(VERSION 3.25)
EOF
  if [[ -f "${FORGE_ROOT}/version.cpp.in" ]]; then
    cat <<EOF
set(forge_tag_line "")
if(EXISTS "\${CMAKE_CURRENT_SOURCE_DIR}/version.cpp.in")
  file(STRINGS "\${CMAKE_CURRENT_SOURCE_DIR}/version.cpp.in" forge_tag_line
    REGEX [=[^inline constexpr char forge_version\\[\\] = "v?[0-9]+(\\.[0-9]+)*";$]=])
endif()
if(forge_tag_line MATCHES [=["v?([0-9]+(\\.[0-9]+)*)"]=])
  project(${name} VERSION \${CMAKE_MATCH_1} LANGUAGES ${languages})
else()
  project(${name} VERSION ${version} LANGUAGES ${languages})
endif()
if(EXISTS "\${CMAKE_CURRENT_SOURCE_DIR}/version.cpp.in")
  configure_file(version.cpp.in forge-version.cpp @ONLY)
endif()
EOF
  else
    printf 'project(%s VERSION %s LANGUAGES %s)\n' "${name}" "${version}" "${languages}"
  fi
  cat <<EOF

set(CMAKE_CXX_STANDARD ${cppstd})
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)
set(CMAKE_EXPORT_COMPILE_COMMANDS ON)

include(CTest)

# Conan packages are supplied by CMakeDeps via the generated toolchain.
# Git/path dependencies are declared here as upstream CMake targets.
include("\${CMAKE_CURRENT_SOURCE_DIR}/cmake/Dependencies.cmake" OPTIONAL)
include("\${CMAKE_CURRENT_SOURCE_DIR}/cmake/Targets.cmake" OPTIONAL)

if(BUILD_TESTING)
  include("\${CMAKE_CURRENT_SOURCE_DIR}/cmake/Testing.cmake" OPTIONAL)
endif()
EOF
}

# Write the debug and release configure presets.
render_cmake_presets() {
  local gen
  gen=$(normalize_generator "$(mq '.build.generator // "Ninja"')")
  jq -n --arg gen "${gen}" '{
    version: 3,
    cmakeMinimumRequired: {major: 3, minor: 25, patch: 0},
    configurePresets: [
      {
        name: "debug", displayName: "Debug", generator: $gen,
        binaryDir: "${sourceDir}/target/debug",
        cacheVariables: {CMAKE_BUILD_TYPE: "Debug"}
      },
      {
        name: "release", displayName: "Release", generator: $gen,
        binaryDir: "${sourceDir}/target/release",
        cacheVariables: {CMAKE_BUILD_TYPE: "Release"}
      }
    ],
    buildPresets: [
      {name: "debug", configurePreset: "debug"},
      {name: "release", configurePreset: "release"}
    ],
    testPresets: [
      {name: "debug", configurePreset: "debug", output: {outputOnFailure: true}},
      {name: "release", configurePreset: "release", output: {outputOnFailure: true}}
    ]
  }'
}

# Write a Conan text recipe for the selected requirements.
render_conanfile() {
  local entry ref opts key val pkg
  local -a entries=()
  if [[ "${FORGE_CONAN_REQUIREMENTS_MODE:-local}" == "graph" \
        && ${#FORGE_CONAN_ALL_REFS[@]} -gt 0 ]]; then
    entries=("${FORGE_CONAN_ALL_REFS[@]}")
  else
    while IFS=$'\t' read -r ref opts; do
      [[ -n "${ref}" ]] && entries+=("${ref}"$'\t'"${opts}")
    done < <(mq '(.dependencies // {}) | to_entries[] | select(.value.source == "conan") | [.value.ref, ((.value.conan_options // {}) | tojson)] | @tsv')
  fi

  {
    printf '# Generated by Forge. Managed by `forge sync`.\n'
    printf '[requires]\n'
    for entry in "${entries[@]}"; do
      IFS=$'\t' read -r ref opts <<< "${entry}"
      [[ -n "${ref}" ]] && printf '%s\n' "${ref}"
    done
    printf '\n[options]\n'
    for entry in "${entries[@]}"; do
      IFS=$'\t' read -r ref opts <<< "${entry}"
      [[ -n "${ref}" ]] || continue
      pkg="${ref%%/*}"
      while IFS=$'\t' read -r key val; do
        [[ -n "${key}" ]] && printf '%s/*:%s=%s\n' "${pkg}" "${key}" "${val}"
      done < <(printf '%s' "${opts}" | jq -r 'to_entries[] | [.key, (.value | if . == true then "True" elif . == false then "False" else tostring end)] | @tsv')
    done
    printf '\n[generators]\nCMakeDeps\nCMakeToolchain\n'
  }
}

# Emit CMake declarations for Conan, Git, and path dependencies.
render_dependencies() {
  local key url rev path member bin_name has_git=0
  {
    printf '# Generated by Forge. Managed by `forge sync`.\n'
    printf '# Conan packages are provided by CMakeDeps via the generated toolchain.\n\n'
    local source package value
    while IFS=$'\t' read -r source package value; do
      [[ -n "${package}" ]] || continue
      if [[ "${source}" == vcpkg ]]; then
        # Conan's toolchain prefers configs globally. vcpkg also supports CMake's Find modules.
        printf 'find_package(%s MODULE QUIET)\n' "${package}"
        printf 'if(NOT TARGET %s)\n  find_package(%s CONFIG REQUIRED)\nendif()\n' "${value}" "${package}"
      elif [[ "${value}" =~ ^[0-9]+(\.[0-9]+){0,3}$ ]]; then
        printf 'find_package(%s %s CONFIG REQUIRED)\n' "${package}" "${value}"
      else
        printf 'find_package(%s CONFIG REQUIRED)\n' "${package}"
      fi
    done < <(mq '
      (.dependencies // {})[]
      | if .source == "conan" then
          (.ref | split("/")) as $ref
          | ["conan", (.cmake_package // $ref[0]), ($ref[1] // "")]
        elif .source == "vcpkg" then ["vcpkg", .cmake_package, .cmake_target]
        else empty end | @tsv
    ')

    while IFS=$'\t' read -r key url rev; do
      [[ -n "${key}" ]] || continue
      if (( has_git == 0 )); then
        printf '\ninclude(FetchContent)\n'
        has_git=1
      fi
      printf 'FetchContent_Declare(%s\n' "${key}"
      printf '  GIT_REPOSITORY %s\n' "${url}"
      printf '  GIT_TAG %s\n' "${rev}"
      printf ')\n'
      printf 'FetchContent_MakeAvailable(%s)\n' "${key}"
    done < <(mq '(.dependencies // {}) | to_entries[] | select(.value.source == "git") | [.key, .value.url, .value.rev] | @tsv')

    while IFS=$'\t' read -r key path; do
      [[ -n "${key}" ]] || continue
      printf '\nadd_subdirectory("${CMAKE_CURRENT_SOURCE_DIR}/%s"\n' "${path}"
      printf '                 "${CMAKE_CURRENT_BINARY_DIR}/%s")\n' "${key}"
    done < <(mq '(.dependencies // {}) | to_entries[] | select(.value.source == "path") | [.key, .value.path] | @tsv')

    while IFS= read -r member; do
      [[ -n "${member}" ]] || continue
      bin_name="${member//\//_}"
      printf '\n# Workspace member: %s\n' "${member}"
      printf 'add_subdirectory("${CMAKE_CURRENT_SOURCE_DIR}/%s"\n' "${member}"
      printf '                 "${CMAKE_CURRENT_BINARY_DIR}/ws_%s")\n' "${bin_name}"
    done < <(workspace_members)
  }
}

# List the workspace members declared in the current manifest.
workspace_members() {
  mq '(.workspace.members // [])[]'
}

# Target names exported by every reachable member (recursively), so any
# project in the graph can link a nested library by name.
workspace_member_targets() {
  local node json
  workspace_collect_graph "${FORGE_ROOT}"
  for node in "${FORGE_GRAPH_NODES[@]}"; do
    [[ "${node}" == "${FORGE_ROOT}" ]] && continue
    [[ -f "${node}/Forge.toml" ]] || continue
    json=$(manifest_to_json "${node}/Forge.toml") || continue
    printf '%s' "${json}" | jq -r '((.bin // []) + (.lib // []) + (.test // []) | .[].name)'
  done
}

# Map logical dependency names to CMake link targets.
_build_link_map() {
  FORGE_LINK_MAP=()
  local key target name
  while IFS=$'\t' read -r key target; do
    [[ -n "${key}" ]] && FORGE_LINK_MAP["${key}"]="${target}"
  done < <(mq '(.dependencies // {}) | to_entries[] | [.key, .value.cmake_target] | @tsv')
  while IFS= read -r name; do
    [[ -n "${name}" ]] && FORGE_LINK_MAP["${name}"]="${name}"
  done < <(mq '((.bin // []) + (.lib // []) + (.test // []) | .[].name)')
  while IFS= read -r name; do
    [[ -n "${name}" ]] && FORGE_LINK_MAP["${name}"]="${name}"
  done < <(workspace_member_targets)
}

# List legacy implicit links. Packages added with an explicit CMake package are scoped to selected targets.
_default_links() {
  local kind="$1" out="" t
  while IFS= read -r t; do
    [[ -n "${t}" ]] && out+=" ${t}"
  done < <(mq '(.dependencies // {})[] | select(has("cmake_package") | not) | .cmake_target')
  if [[ "${kind}" == "test" ]]; then
    while IFS= read -r t; do
      [[ -n "${t}" ]] && out+=" ${t}"
    done < <(mq '(.lib // [])[] | .name')
  fi
  printf '%s' "${out# }"
}

# Resolve the dependency aliases in a target's links array.
_resolve_links() {
  local kind="$1" links="$2" has_links="$3" out="" t
  local -a arr=()
  if [[ "${has_links}" == "true" ]]; then
    read -r -a arr <<< "${links}"
    for t in "${arr[@]}"; do
      out+=" ${FORGE_LINK_MAP[${t}]:-${t}}"
    done
  else
    read -r -a arr <<< "$(_default_links "${kind}")"
    for t in "${arr[@]}"; do
      out+=" ${t}"
    done
  fi
  printf '%s' "${out# }"
}

# Emit the CMake rules for the manifest's libraries, binaries, and tests.
render_targets() {
  _build_link_map
  local kind name path links has_links resolved command linkage
  printf '# Generated by Forge. Managed by `forge sync`.\n'
  while IFS=$'\t' read -r kind name path linkage has_links links; do
    [[ -n "${name}" ]] || continue
    # An empty links array historically uses the legacy dependency defaults.
    if [[ -z "${links}" ]]; then has_links=false; fi
    resolved=$(_resolve_links "${kind}" "${links}" "${has_links}")
    command=executable
    if [[ "${kind}" == lib ]]; then command=library; fi
    if [[ "${linkage}" == legacy ]]; then
      printf '\nadd_%s(%s %s)\n' "${command}" "${name}" "${path}"
    else
      printf '\nadd_library(%s %s %s)\n' "${name}" "${linkage}" "${path}"
      case "${linkage}" in
        STATIC) printf 'set_target_properties(%s PROPERTIES POSITION_INDEPENDENT_CODE ON)\n' "${name}" ;;
        SHARED) printf 'set_target_properties(%s PROPERTIES WINDOWS_EXPORT_ALL_SYMBOLS ON)\n' "${name}" ;;
      esac
    fi
    case "${kind}" in
      lib) printf 'target_include_directories(%s PUBLIC "${CMAKE_CURRENT_SOURCE_DIR}/include")\n' "${name}" ;;
      bin)
        if [[ -f "${FORGE_ROOT}/version.cpp.in" ]]; then
          printf 'target_include_directories(%s PRIVATE "${CMAKE_CURRENT_BINARY_DIR}")\n' "${name}"
        fi ;;
    esac
    if [[ -n "${resolved}" ]]; then
      printf 'target_link_libraries(%s PRIVATE %s)\n' "${name}" "${resolved}"
    fi
  done < <(mq '
    ["lib", "bin", "test"][] as $kind | (.[$kind] // [])[]
    | [$kind, .name, .path, (if has("type") then .type | ascii_upcase else "legacy" end), (has("links") | tostring), ((.links // []) | join(" "))] | @tsv
  ')
}

# Register manifest test executables with CTest.
render_testing() {
  local name found=0
  {
    printf '# Generated by Forge. Managed by `forge sync`.\n'
    while IFS= read -r name; do
      [[ -n "${name}" ]] || continue
      printf 'add_test(NAME %s COMMAND %s)\n' "${name}" "${name}"
      found=1
    done < <(mq '(.test // [])[] | .name')
    (( found )) || printf '# No [[test]] targets are declared in Forge.toml.\n'
  }
}

# Render the Forge-managed files for one project.
cmake_render_all() {
  local dir="$1"
  mkdir -p "${dir}/cmake"
  render_cmake_lists      > "${dir}/CMakeLists.txt"
  render_cmake_presets    > "${dir}/CMakePresets.json"
  render_conanfile        > "${dir}/conanfile.txt"
  render_dependencies     > "${dir}/cmake/Dependencies.cmake"
  render_targets          > "${dir}/cmake/Targets.cmake"
  render_testing          > "${dir}/cmake/Testing.cmake"
}

# --- Fingerprint / configure ----------------------------------------------
compute_fingerprint() {
  local profile="$1" toolchain="${2:-}" parts="" conan_script=""
  parts+="compiler=$(c++ --version 2>/dev/null | head -1)"
  parts+="|generator=$(normalize_generator "$(mq '.build.generator // "Ninja"')")"
  parts+="|arch=$(uname -m)"
  parts+="|profile=${profile}"
  if [[ -n "${toolchain}" ]]; then
    parts+="|toolchain=$(sha256_file "${toolchain}")"
  fi
  if [[ -n "${FORGE_SANITIZER:-}" ]]; then
    parts+="|sanitizer=${FORGE_SANITIZER}"
  fi
  if (( $(mq '[(.dependencies // {}) | to_entries[] | select(.value.source == "conan")] | length') > 0 )); then
    conan_script=$(conan profile show 2>/dev/null)
    parts+="|conan=$(sha256_str "${conan_script}")"
  fi
  local vcpkg_manifest vcpkg_toolchain
  vcpkg_manifest=$(vcpkg_workspace_manifest) || return "${EXIT_DEP}"
  if [[ -n "${vcpkg_manifest}" ]]; then
    vcpkg_toolchain="${VCPKG_ROOT:-}/scripts/buildsystems/vcpkg.cmake"
    parts+="|vcpkg=${VCPKG_ROOT:-}:${vcpkg_manifest}"
    if [[ -f "${vcpkg_toolchain}" ]]; then
      parts+=":$(sha256_file "${vcpkg_toolchain}")"
      parts+=":$(git -C "${VCPKG_ROOT}" rev-parse HEAD 2>/dev/null || true)"
    fi
  fi
  sha256_str "${parts}" | cut -c1-12
}

# Compute the build directory for the requested or default profile.
resolve_build_dir() {
  # Optional profile override; defaults to manifest default_profile / debug.
  local profile="${1:-}"
  [[ -n "${profile}" ]] || profile=$(mq '.build.default_profile // "debug"')
  local fp
  fp=$(compute_fingerprint "${profile}") || return $?
  printf '%s' "${FORGE_ROOT}/target/${profile}-${fp}"
}

# Check that both the CMake cache and generator output exist.
cmake_is_configured() {
  local build_dir="$1" gen="$2" marker
  [[ -f "${build_dir}/CMakeCache.txt" ]] || return 1
  case "${gen}" in
    Ninja*) marker="build.ninja" ;;
    *)      marker="Makefile" ;;
  esac
  [[ -f "${build_dir}/${marker}" ]] || return 1
  return 0
}

# Request a codemodel reply at the next CMake configure.
cmake_prepare_file_api() {
  local build_dir="$1"
  mkdir -p "${build_dir}/.cmake/api/v1/query"
  : > "${build_dir}/.cmake/api/v1/query/codemodel-v2"
}

# Configure the project through a preset in the fingerprinted build directory.
cmake_configure() {
  local build_dir="$1" profile="$2" gen="$3" toolchain="${4:-}" reply
  local vcpkg_manifest
  vcpkg_manifest=$(vcpkg_workspace_manifest) || die "${EXIT_DEP}" "could not resolve vcpkg manifest"
  if (( ! FORGE_DRY_RUN )); then
    if [[ -n "${vcpkg_manifest}" ]]; then
      vcpkg_prepare_configure "${build_dir}" "${toolchain}" "${vcpkg_manifest}"
      toolchain=""
    fi
    cmake_prepare_file_api "${build_dir}"
  fi
  local -a args=(--preset "${profile}" -S "${FORGE_ROOT}" -B "${build_dir}")
  [[ -n "${toolchain}" ]] && args+=("-DCMAKE_TOOLCHAIN_FILE=${toolchain}")
  args+=("${FORGE_EXTRA_CMAKE_ARGS[@]}")
  run_cmd cmake "${args[@]}" \
    || die "${EXIT_BUILD}" "CMake configure failed for '${profile}'"
}

# List executable target names from the CMake File API reply.
cmake_list_executables() {
  local build_dir="$1" reply dir jf
  reply=$(find "${build_dir}/.cmake/api/v1/reply" -name 'codemodel-v2-*.json' -print -quit 2>/dev/null)
  [[ -n "${reply}" ]] || return 1
  dir=$(dirname -- "${reply}")
  while IFS= read -r jf; do
    [[ -f "${dir}/${jf}" ]] || continue
    [[ "$(jq -r '.type' "${dir}/${jf}")" == "EXECUTABLE" ]] || continue
    jq -r '.name' "${dir}/${jf}"
  done < <(jq -r '.configurations[0].targets[] | .jsonFile' "${reply}")
}

# Resolve an executable's real path from the CMake File API codemodel.
cmake_executable_path() {
  local name="$1" build_dir="$2" reply dir jf n artifact
  reply=$(find "${build_dir}/.cmake/api/v1/reply" -name 'codemodel-v2-*.json' -print -quit 2>/dev/null)
  [[ -n "${reply}" ]] || return 1
  dir=$(dirname -- "${reply}")
  while IFS= read -r jf; do
    [[ -f "${dir}/${jf}" ]] || continue
    n=$(jq -r '.name' "${dir}/${jf}")
    [[ "${n}" == "${name}" ]] || continue
    [[ "$(jq -r '.type' "${dir}/${jf}")" == "EXECUTABLE" ]] || continue
    artifact=$(jq -r '.artifacts[0].path // empty' "${dir}/${jf}")
    [[ -n "${artifact}" ]] || return 1
    # Artifact paths are relative to the top-level build directory or absolute.
    if [[ "${artifact}" == /* ]]; then
      printf '%s\n' "${artifact}"
    else
      printf '%s\n' "${build_dir}/${artifact}"
    fi
    return 0
  done < <(jq -r '.configurations[0].targets[] | .jsonFile' "${reply}")
  return 1
}

# Look for a built executable in common generator output locations.
find_executable() {
  local name="$1" build_dir="$2" c
  for c in "${build_dir}/${name}" "${build_dir}/${name}.exe" \
           "${build_dir}/Debug/${name}" "${build_dir}/Release/${name}"; do
    [[ -x "${c}" ]] && { printf '%s\n' "${c}"; return 0; }
  done
  c=$(find "${build_dir}" -maxdepth 3 -type f -name "${name}" -perm -u+x -print -quit 2>/dev/null)
  [[ -n "${c}" ]] && { printf '%s\n' "${c}"; return 0; }
  return 1
}

# Expose the compilation database at the project root.
link_compile_commands() {
  local build_dir="$1" src="${1}/compile_commands.json"
  local dst="${FORGE_ROOT}/compile_commands.json"
  [[ -f "${src}" ]] || return 0
  if [[ -e "${dst}" || -L "${dst}" ]]; then
    if (( FORGE_LINK_COMPILE_COMMANDS )); then
      rm -f -- "${dst}" || { warn "could not replace compile_commands.json"; return 0; }
    else
      warn "compile_commands.json already exists at project root; not replacing"
      return 0
    fi
  fi
  local rel="${src#${FORGE_ROOT}/}"
  ln -s "${rel}" "${dst}" 2>/dev/null \
    || warn "could not link compile_commands.json"
}
